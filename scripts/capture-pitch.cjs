const { chromium } = require('playwright');
const fs = require('node:fs/promises');
const path = require('node:path');
const assert = require('node:assert/strict');
const base = 'http://127.0.0.1:3201';
const out = path.resolve('output/pitch');
process.env.PW_TEST_SCREENSHOT_NO_FONTS_READY='1';
let browser;
(async()=>{
  await fs.mkdir(out,{recursive:true});
  browser = await chromium.launch({headless:true,channel:'msedge'});
  const context = await browser.newContext({viewport:{width:1600,height:1100},deviceScaleFactor:2,reducedMotion:'reduce',acceptDownloads:true});
  const page = await context.newPage();
  const responses=[];
  page.on('response',async response=>{
    if(response.url().endsWith('/api/transition')) try{responses.push(await response.json());}catch{}
  });
  page.setDefaultTimeout(15000);
  await page.goto(base+'/#import',{waitUntil:'domcontentloaded'});
  await page.getByRole('button',{name:/^SR A career change Siti Rosli/}).click();
  await fs.writeFile(path.join(out,'intake-text.txt'),await page.locator('body').innerText());
  await page.screenshot({path:path.join(out,'intake.png'),fullPage:true});
  await page.getByRole('button',{name:'Looks right, continue',exact:true}).click();
  await page.getByRole('button',{name:'4 hours / week',exact:true}).click();
  await page.screenshot({path:path.join(out,'preferences.png'),fullPage:true});
  const changed=async(action,predicate=()=>true)=>{
    const promise=page.waitForResponse(r=>r.url().endsWith('/api/transition')&&predicate(r.request().postDataJSON()));
    await action(); const data=await(await promise).json();
    await page.locator('.c-api-receipt').waitFor();return data;
  };
  const nav=async(name)=>{await page.getByRole('link',{name:new RegExp('^'+name)}).click();};
  const snap=async(name,selector)=>{
    if(selector) await (selector==='dialog'?page.getByRole('dialog'):page.locator(selector)).screenshot({path:path.join(out,name+'.png')});
    else await page.screenshot({path:path.join(out,name+'.png'),fullPage:true});
  };
  const cut=async(name,selector,height,offset=0)=>{
    const box=await (selector==='dialog'?page.getByRole('dialog'):page.locator(selector)).boundingBox();
    await page.screenshot({path:path.join(out,name+'.png'),clip:{x:box.x,y:box.y+offset,width:box.width,height}});
  };
  const initial=await changed(()=>page.getByRole('button',{name:'Create my career workspace',exact:true}).click());
  await nav('Future roles');
  await page.locator('.c-role-select').filter({hasText:'Financial data analyst'}).click();
  await snap('roles'); await snap('role-detail','.c-role-detail');
  await cut('role-summary','.c-role-detail',282);
  await fs.writeFile(path.join(out,'role-text.txt'),await page.locator('.c-role-detail').innerText());
  await nav('Skills radar'); await snap('radar');
  await snap('evidence-status','.c-live-evidence');
  await page.locator('.c-evidence-row').filter({hasText:'Research'}).nth(3).click();
  await snap('source-detail','dialog');
  await snap('source-mapping','.c-evidence-mappings');
  await page.locator('.c-evidence-mappings > div').nth(1).screenshot({path:path.join(out,'source-relevant-mapping.png')});
  await snap('source-receipt','.c-evidence-receipt');
  const dialogBox=await page.getByRole('dialog').boundingBox();
  const bylineBox=await page.locator('.c-source-byline').boundingBox();
  await cut('source-title','dialog',bylineBox.y+bylineBox.height-dialogBox.y+12);
  await page.keyboard.press('Escape');
  await nav('Learning plan');
  await snap('initial-plan');
  await snap('initial-step','.c-learning-step.open');
  const completed=await changed(()=>page.getByRole('button',{name:'Mark step complete',exact:true}).first().click(),b=>b.completedStepIds.length>0);
  await snap('completed-plan'); await snap('completed-step','.c-learning-step.complete');
  await cut('completed-step-header','.c-learning-step.complete',118);
  const rapid=await changed(()=>page.getByRole('button',{name:'Faster AI adoption',exact:true}).click(),b=>b.scenarioId==='rapid');
  await page.getByRole('button',{name:'Review changes',exact:true}).click();
  await snap('revision-dialog','dialog');
  await snap('revision-comparison','.c-change-comparison');
  await snap('revision-proof','.c-revision-proof');
  await snap('revision-actions','dialog[open] .c-dialog-actions');
  await fs.writeFile(path.join(out,'revision-text.txt'),await page.getByRole('dialog').innerText());
  await page.getByRole('button',{name:'Accept & update my plan',exact:true}).click();
  assert.equal(await page.locator('.c-learning-step.complete').count(),1);
  await snap('accepted-plan'); await snap('sql-step','.c-learning-step.open');
  await cut('sql-step-focus','.c-learning-step.open',460);
  await page.getByRole('button',{name:'Save my plan',exact:true}).click();
  await page.keyboard.press('Escape');
  const dl=page.waitForEvent('download');
  await page.getByRole('button',{name:'Download brief',exact:true}).click();
  const download=await dl; await download.saveAs(path.join(out,'siti-career-brief.md'));
  await page.reload({waitUntil:'domcontentloaded'});await page.locator('.c-api-receipt').waitFor();
  assert.equal(await page.locator('.c-learning-step.complete').count(),1);
  const green=await changed(()=>page.getByRole('button',{name:'Green transition',exact:true}).click(),b=>b.scenarioId==='green');
  await page.getByRole('button',{name:'Review changes',exact:true}).click();
  await snap('revert-dialog','dialog');
  const reverted=await changed(()=>page.getByRole('button',{name:'Keep previous view',exact:true}).click(),b=>b.scenarioId==='rapid');
  assert.equal(await page.locator('.c-learning-step.complete').count(),1);
  const state=await page.evaluate(()=>JSON.parse(localStorage.getItem('nexus-workspace-v2')));
  assert.equal(state.scenario,'rapid');assert.equal(state.preferences.hours,4);assert.equal(state.profile.id,'siti');
  await fs.writeFile(path.join(out,'demo-proof.json'),JSON.stringify({capturedAt:new Date().toISOString(),base,initial,completed,rapid,green,reverted,state,checks:{acceptPreserved:true,reloadPreserved:true,revertPreserved:true}},null,2));
  console.log(JSON.stringify({status:initial.evidence.status,revision:initial.evidence.revision,score:initial.matches.find(r=>r.id==='financial').score,rapidScore:rapid.matches.find(r=>r.id==='financial').score,checks:{accept:true,reload:true,revert:true}},null,2));
  await fs.writeFile(path.join(out,'responses.json'),JSON.stringify(responses,null,2));
  await browser.close();
})().catch(async e=>{console.error(e);await browser?.close();process.exitCode=1});
